//! The remaining fullscreen depth-reconstruction passes under the single-pass collapse: SSAO and
//! screen-space reflections, run once with each eye's half computed for that eye, and screen-space
//! subsurface skin and the bokeh depth-of-field prepass, run once per eye.
//!
//! Cross-referencing `CMatrix4f::PerspectiveFovInverse` gives a closed set of seven consumers. The
//! deferred resolve ([`crate::hooks::graphics_engine::clustered_lighting`]) and the aerial perspective
//! ([`crate::hooks::graphics_engine::atmospheric_scattering`]) are split per eye in their own modules; the wireframe-only
//! `DrawPassThrough` never runs during shaded rendering; these are the rest. Collapsed, each of them
//! is one draw spanning **both** eye halves of the double-wide target while the substituted basis
//! describes one eye's frustum, so neither half reconstructs correctly and the error turns with the
//! camera.
//!
//! **SSAO** is not split. Its occlusion is generated by a pixel shader that reconstructs from the
//! render context's projection and view directly (its one `PerspectiveFovInverse` call feeds only the
//! temporal resolve's reprojection), so a split would need the render context restaged per run, and
//! the shader's tap offsets, seam taps, and pixel-position noise are wrong under a double-wide target
//! whatever basis it is handed. [`crate::stereo::single_pass::ambient_occlusion`] rewrites that shader
//! to compute each half for its own eye from a per-eye constant pair, and [`ssao_block_draw`] binds
//! the pair for the block, so the block keeps its single run and its temporal history advances once
//! per frame as it does in an eye-sized render.
//!
//! **Screen-space reflections** are not split either. The ray march projects and reprojects through
//! the render context's view, projection, camera transform, and two view-projections, none of which a
//! substituted basis reaches, and marches in the pixels of the whole target.
//! [`crate::stereo::single_pass::screen_space_reflection`] rewrites it to trace each half for its own
//! eye from per-eye rows, and [`ssr_draw`] binds them for the block.
//!
//! The split blocks are behind their own config flags, because unlike the two already landed they are
//! not idempotent -- re-issuing the whole block re-runs work that accumulates. **Subsurface skin**
//! builds its basis once per `Draw`, not once per blur axis: the two `PerspectiveFovInverse` calls in
//! the function sit in mutually exclusive branches.
//!
//! The rest of the non-idempotency is handled by *when* the mask goes up. These run under
//! [`reconstruction::MaskArming::AtEntry`]: the eye mask is raised before the block draws anything and
//! re-derived from every render target the block binds, so the two runs are disjoint over the whole
//! block and each pixel is written exactly once. That is what the blur ping-pongs need -- two
//! *overlapping* runs would blur an already-blurred result -- and it is the only rule that can work at
//! all here, because each block draws through targets of several different sizes in one `Draw` while
//! a scissor rectangle means nothing outside the target it was measured in.
//!
//! The compute work is not maskable at all -- a dispatch ignores the scissor as thoroughly as it
//! ignores the viewport -- and the bokeh prepass offers no way to aim one: it sizes its thread groups
//! from the target's full width and addresses its textures straight off `SV_DispatchThreadID`, with no
//! origin term anywhere in its constant buffers. Nor can a UAV supply one, since a D3D11 texture UAV
//! selects a mip and an array slice and never a sub-rectangle. So the compute work is *scheduled*
//! rather than masked: [`reconstruction::DispatchPhase`] issues it whole-target on exactly one run of
//! the split, the first, since its output (the bokeh near-field coverage) is what the masked draws
//! consume. That is the same single whole-target pass the un-split block makes, so the eye-seam bleed
//! from the horizontal half of each separable blur is inherent to the collapse rather than introduced
//! here, and is present with these flags off.

use detours_macro::detour;
use jc3gi::graphics_engine::{
    graphics_engine::{HContext_t, RenderContext},
    post_effects::{DownScale2x2PackFocus, PostEffectContext, PostEffectsManager},
    render_block::{
        RBIInfo, RenderBlockSSAO, RenderBlockScreenSpaceReflection,
        RenderBlockScreenSpaceSubSurfaceSkin,
    },
};
use re_utilities::hook_library::HookLibrary;

use crate::{
    hooks::graphics_engine::{
        probes::{self, scoped},
        reconstruction,
    },
    stereo::{
        config::STEREO_CONFIG,
        single_pass::{ambient_occlusion, screen_space_reflection},
    },
};

pub(super) fn hook_library() -> HookLibrary {
    HookLibrary::new()
        .with_static_binder(&SSAO_BLOCK_DRAW_BINDER)
        .with_static_binder(&SSR_DRAW_BINDER)
        .with_static_binder(&SUBSURFACE_DRAW_BINDER)
        .with_static_binder(&DOF_DOWNSCALE_APPLY_BINDER)
}

/// `CRenderBlockSSAO::Draw`, run once with each eye's reconstruction rows bound for its rewritten
/// generation shader.
///
/// Without the rewrite live (the switch off, no collapse, or the shaders not yet reloaded) nothing is
/// bound and the block runs as the engine issues it.
#[detour(address = jc3gi::graphics_engine::render_block::RenderBlockSSAO::Draw_ADDRESS)]
fn ssao_block_draw(this: *mut RenderBlockSSAO, rc: *mut RenderContext, info: *const RBIInfo) {
    let enabled = STEREO_CONFIG.query(|c| c.single_pass.ssao_per_eye)
        && crate::stereo::layout::collapse_active();
    let _rows = enabled.then(ambient_occlusion::bind_eye_rows).flatten();
    scoped(
        probes::armed(),
        |probes, body| probes.ambient_occlusion_scope(body),
        || SSAO_BLOCK_DRAW.get().unwrap().call(this, rc, info),
    );
}

/// `CRenderBlockScreenSpaceReflection::Draw`, run once with each eye's rows bound for its rewritten
/// ray march.
///
/// The ray march traces each half of the double-wide target for its own eye
/// ([`screen_space_reflection`]), the scene-colour capture before it is per pixel, and the blur after
/// it keeps its taps to the eye's half, so the block keeps its single run. Without the rewrite live
/// (the switch off, no collapse, or the shaders not yet reloaded) nothing is bound and the block runs
/// as the engine issues it.
#[detour(
    address = jc3gi::graphics_engine::render_block::RenderBlockScreenSpaceReflection::Draw_ADDRESS
)]
fn ssr_draw(
    this: *mut RenderBlockScreenSpaceReflection,
    rc: *mut RenderContext,
    info: *const RBIInfo,
) {
    let enabled = STEREO_CONFIG.query(|c| c.single_pass.ssr_per_eye)
        && crate::stereo::layout::collapse_active();
    // SAFETY: the engine hands the block its live render context for the length of the call.
    let context = unsafe { rc.as_ref() };
    let _rows = context
        .filter(|_| enabled)
        .and_then(screen_space_reflection::bind_eye_rows);
    scoped(
        probes::armed(),
        |probes, body| probes.screen_space_reflection_scope(body),
        || SSR_DRAW.get().unwrap().call(this, rc, info),
    );
}

/// `CRenderBlockScreenSpaceSubSurfaceSkin::Draw`, split per eye.
///
/// Both of the block's paths call `PerspectiveFovInverse` exactly once, before their first
/// render-setup bind, and the at-entry mask covers every draw of the diffusion chain -- following the
/// six separable blur draws onto the SSS targets they ping-pong between, so neither run re-blurs the
/// other's output.
#[detour(
    address = jc3gi::graphics_engine::render_block::RenderBlockScreenSpaceSubSurfaceSkin::Draw_ADDRESS
)]
fn subsurface_draw(
    this: *mut RenderBlockScreenSpaceSubSurfaceSkin,
    rc: *mut RenderContext,
    info: *const RBIInfo,
) {
    let enabled = STEREO_CONFIG.lock().single_pass.subsurface_per_eye;
    let call = || SUBSURFACE_DRAW.get().unwrap().call(this, rc, info);
    split_or_issue(enabled, render_context_ctx(rc), call);
}

/// `CDownScale2x2PackFocus::Apply`, the bokeh downscale prepass, split per eye with its compute
/// prologue left to the first run.
///
/// This is the depth-of-field basis's home: the prepass's closing fullscreen draw is the sole consumer
/// of `DOFUtil::GetViewProjInverse`, which it uploads as vertex constants 1..4 and which the shared
/// `PerspectiveFovInverse` detour already substitutes the off-axis inverse into. Under the collapse
/// that one draw spans both halves with one eye's basis, so the haze the pack folds into the
/// downscaled colour is derived from the wrong world ray over most of the frame.
///
/// The prepass's five compute dispatches -- the near-field circle-of-confusion extract plus four
/// separable blur passes ping-ponging two quarter-resolution textures -- are unmaskable, which
/// makes the pass look unsplittable. But they do not need a mask:
/// none of them reads a view or projection matrix (the extract takes the depth texture and the focal
/// tuning; the blur takes a step direction and its source texture), so their whole-target result is
/// already right for both eyes. [`reconstruction::DispatchPhase::FirstRun`] therefore issues them on
/// eye 0's run and suppresses them on eye 1's, which then reads the same blurred coverage instead of
/// blurring it a second time -- while both runs draw the pack masked to their own half with their own
/// basis. The blur's six-texel reach across the eye seam is left as it is: the un-split prepass has it
/// too, because the collapse hands the dispatch one double-wide texture either way.
#[detour(address = jc3gi::graphics_engine::post_effects::DownScale2x2PackFocus::Apply_ADDRESS)]
fn dof_downscale_apply(
    this: *mut DownScale2x2PackFocus,
    ctx: *mut HContext_t,
    pec: *mut PostEffectContext,
    mgr: *mut PostEffectsManager,
) {
    let enabled = STEREO_CONFIG.lock().single_pass.dof_per_eye;
    let call = || DOF_DOWNSCALE_APPLY.get().unwrap().call(this, ctx, pec, mgr);
    split_or_issue_with(
        reconstruction::DispatchPhase::FirstRun,
        enabled,
        Some(ctx),
        call,
    );
}

/// [`split_or_issue_with`] for a block that issues no dispatches.
fn split_or_issue(enabled: bool, ctx: Option<*mut HContext_t>, draw: impl FnMut()) {
    split_or_issue_with(reconstruction::DispatchPhase::Both, enabled, ctx, draw);
}

/// Run `draw` once per eye half under the collapse, falling back to issuing it exactly once.
///
/// Every caller here goes through [`reconstruction::SplitPolicy::at_entry`], which is the split's only
/// constructor of [`MaskArming::AtEntry`](reconstruction::MaskArming::AtEntry) -- so this path can never
/// demote in the [`MaskArming::OnReconstruction`](reconstruction::MaskArming::OnReconstruction) sense of
/// a single unmasked run: under `AtEntry` the two runs are disjoint by construction, so the mask either
/// goes up before the first run draws anything -- in which case both runs happen -- or it never goes up
/// at all and nothing is drawn. [`reconstruction::SplitOutcome::NotTaken`] is therefore the only outcome
/// that means the caller's own issue is still needed; every other outcome means `draw` already ran and
/// must not run again.
fn split_or_issue_with(
    dispatches: reconstruction::DispatchPhase,
    enabled: bool,
    ctx: Option<*mut HContext_t>,
    mut draw: impl FnMut(),
) {
    let outcome = reconstruction::split_fullscreen_pass_policy(
        reconstruction::SplitPolicy::at_entry(dispatches),
        enabled,
        ctx,
        |_eye| draw(),
    );
    if outcome == reconstruction::SplitOutcome::NotTaken {
        draw();
    }
}

/// The graphics context a render block's dispatch is drawing on.
fn render_context_ctx(rc: *mut RenderContext) -> Option<*mut HContext_t> {
    // SAFETY: `rc` is the live render context for this dispatch; the engine's draw dispatch guarantees
    // it is valid for the duration of the block's `Draw`.
    unsafe { rc.as_ref() }.map(|rc| rc.m_Context)
}
